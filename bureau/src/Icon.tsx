/** Pastille ronde avec les initiales, couleur stable par nom. */
export function Avatar({ name, size = 28 }: { name: string; size?: number }) {
  const initials = name.split(/[\s(]+/).filter(Boolean).slice(0, 2).map((w) => w[0]?.toUpperCase()).join('') || '?';
  let h = 0;
  for (const c of name) h = (h * 31 + c.charCodeAt(0)) % 360;
  return (
    <span className="avatar" style={{ width: size, height: size, fontSize: Math.round(size * 0.38), background: `hsl(${h} 50% 90%)`, color: `hsl(${h} 45% 30%)` }} title={name}>
      {initials}
    </span>
  );
}

