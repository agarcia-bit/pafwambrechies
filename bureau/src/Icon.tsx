export function Skeleton({ lines = 3 }: { lines?: number }) {
  return (
    <div className="skeleton" aria-busy>
      {Array.from({ length: lines }, (_, i) => <span key={i} style={{ width: `${90 - (i % 3) * 18}%` }} />)}
    </div>
  );
}

